class OrcaIO:
    """Construct, write, and organize ORCA input files."""

    def __init__(self, config=None, root="calculations"):
        self.config = {**CONFIG, **(config or {})}
        self.root = Path(root)

    # ========================================================
    # ORCA input construction
    # ========================================================

    def make_orcasimpleinput(self, state=None):
        """Build the ORCA simple-input line."""
        state = state or {}

        keywords = state.get(
            "keywords",
            [
                self.config["dispersion"],
                self.config["scf"],
                self.config["optimization"],
            ],
        )

        return " ".join([
            state.get("method", self.config["method"]),
            state.get("basis", self.config["basis"]),
            *keywords,
        ])

    def make_orcablocks(self, state):
        """Build ORCA % blocks from a state configuration."""
        blocks = [
            f"%pal nprocs {self.config['nprocs']} end",
            f"%maxcore {self.config['maxcore']}",
        ]

        for block_name, options in state.get("blocks", {}).items():
            lines = [f"%{block_name}"]

            for key, value in options.items():
                lines.append(f"    {key} {value}")

            lines.append("end")
            blocks.append("\n".join(lines))

        return "\n\n".join(blocks)

    def make_compound_input(self, atoms, steps):
        """Generate an ORCA Compound input string."""
        lines = [
            "# Generated by OrcaIO",
            "",
            "%pal",
            f"    nprocs {self.config['nprocs']}",
            "end",
            f"%maxcore {self.config['maxcore']}",
            "",
            "%Compound",
        ]

        for index, step in enumerate(steps):
            lines.extend([
                "",
                f"    # Step {index + 1}: {step['name']}",
                "    NewStep",
                (
                    f"        ! {step.get('method', self.config['method'])} "
                    f"{step.get('basis', self.config['basis'])} "
                    + " ".join(
                        step.get(
                            "keywords",
                            [
                                self.config["dispersion"],
                                self.config["scf"],
                            ],
                        )
                    )
                ),
            ])

            # Only the first step defines the initial geometry.
            if index == 0:
                lines.append(
                    f"        * xyz {step.get('charge', 0)} "
                    f"{step.get('mult', 1)}"
                )

                for symbol, position in zip(
                    atoms.get_chemical_symbols(),
                    atoms.get_positions(),
                ):
                    x, y, z = position
                    lines.append(
                        f"            {symbol:2s} "
                        f"{x: .10f} {y: .10f} {z: .10f}"
                    )

                lines.append("        *")

            # Optional geometry reset to an earlier Compound step.
            if "read_geom" in step:
                # Note: Read_Geom must be positioned before NewStep
                # in the final Compound input. See note below.

                pass

            for block_name, options in step.get("blocks", {}).items():
                lines.append(f"        %{block_name}")

                for key, value in options.items():
                    lines.append(f"            {key} {value}")

                lines.append("        end")

            lines.append("    StepEnd")

        lines.extend(["End", ""])
        return "\n".join(lines)

    # ========================================================
    # File writing
    # ========================================================

    def write_orca_input(self, filename, atoms, state):
        """Write a conventional, standalone ORCA input."""
        filename = Path(filename)
        filename.parent.mkdir(parents=True, exist_ok=True)

        params = {
            "orcasimpleinput": self.make_orcasimpleinput(state),
            "orcablocks": self.make_orcablocks(state),
            "charge": state.get("charge", 0),
            "mult": state.get("mult", 1),
        }

        with filename.open("w") as fd:
            write_orca(fd, atoms, params)

        print(f"Created: {filename}")
        return filename

    def write_compound_input(self, filename, atoms, steps):
        """Write an ORCA Compound input."""
        filename = Path(filename)
        filename.parent.mkdir(parents=True, exist_ok=True)

        filename.write_text(
            self.make_compound_input(atoms, steps)
        )

        print(f"Created: {filename}")
        return filename

    # ========================================================
    # Calculation organization
    # ========================================================

    def prepare_calculation(self, atoms, molecule_id, inputs):
        """
        Create separate input files for the supplied electronic states.

        Parameters
        ----------
        atoms : ase.Atoms
            Geometry used to initialize the calculations.
        molecule_id : str
            Molecule identifier.
        inputs : dict
            Mapping of state names to ORCA state configurations.
        """
        created_files = {}
        molecule_dir = self.root / molecule_id

        for state_name, state in inputs.items():
            state_dir = molecule_dir / state_name
            input_file = state_dir / "opt.inp"

            self.write_orca_input(input_file, atoms, state)
            created_files[state_name] = input_file

        return created_files

    def prepare_compound_calculation(
        self, atoms, molecule_id, calculation_name, steps
    ):
        """Create a Compound input in its own calculation directory."""
        calculation_dir = self.root / molecule_id / calculation_name
        input_file = calculation_dir / "calc.inp"

        return self.write_compound_input(
            input_file,
            atoms,
            steps,
        )
    
class ORCARunner:
    """Responsible only for executing ORCA calculations."""

    def __init__(self, executable="orca"):
        self.executable = shutil.which(executable)
        if self.executable is None:
            raise FileNotFoundError(
                f"ORCA executable not found: {executable}"
            )

    def run(self, input_file, timeout=None):
        input_file = Path(input_file).resolve()

        if not input_file.is_file():
            raise FileNotFoundError(input_file)

        output_file = input_file.with_suffix(".out")
        log_file = input_file.with_suffix(".launcher.log")

        with log_file.open("w") as log:
            result = subprocess.run(
                [self.executable, input_file.name],
                cwd=input_file.parent,
                stdout=log,
                stderr=subprocess.STDOUT,
                timeout=timeout,
                check=False,
            )

        if not output_file.is_file():
            raise RuntimeError(
                f"ORCA output was not created: {output_file}"
            )

        if result.returncode != 0:
            raise RuntimeError(
                f"ORCA failed with exit code {result.returncode}. "
                f"See {output_file} and {log_file}"
            )

        return output_file

class ORCAValidator:
    """Validates ORCA output before subsequent steps are generated."""

    @staticmethod
    def validate_termination(output_file):
        text = Path(output_file).read_text(errors="replace")

        if "ORCA TERMINATED NORMALLY" not in text:
            raise RuntimeError(
                f"ORCA did not terminate normally: {output_file}"
            )

        if "FINAL SINGLE POINT ENERGY" not in text:
            raise RuntimeError(
                f"Final energy not found: {output_file}"
            )

        return True

    @staticmethod
    def validate_optimization(output_file):
        ORCAValidator.validate_termination(output_file)

        text = Path(output_file).read_text(errors="replace")
        if "THE OPTIMIZATION HAS CONVERGED" not in text:
            raise RuntimeError(
                f"Optimization convergence not confirmed: {output_file}"
            )

        return True

    @staticmethod
    def validate_tddft(output_file, expected_roots=5):
        ORCAValidator.validate_termination(output_file)

        text = Path(output_file).read_text(errors="replace")

        # Preliminary check only; later, parse singlet and triplet
        # sections separately to verify the requested roots.
        import re

        roots = {
            int(n)
            for n in re.findall(
                r"^\s*STATE\s+(\d+)\s*:",
                text,
                flags=re.MULTILINE,
            )
        }

        if len(roots) < expected_roots:
            raise RuntimeError(
                f"Expected at least {expected_roots} distinct "
                f"TDDFT roots; found {len(roots)}."
            )

        return True

class TADFWorkflow:
    """Coordinate S0, vertical TDDFT, and excited-state calculations."""

    def __init__(
        self,
        atoms,
        molecule_id,
        workdir="calculations",
        io=None,
        runner=None,
        validator=None,
    ):
        self.atoms = atoms
        self.molecule_id = molecule_id
        self.root = Path(workdir).resolve() / molecule_id

        self.io = io or OrcaIO(root=Path(workdir))
        self.runner = runner or ORCARunner()
        self.validator = validator or ORCAValidator()

        self.root.mkdir(parents=True, exist_ok=True)

