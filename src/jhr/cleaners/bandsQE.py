from jhr.cleaners._bands import _findBandgap
import numpy as np



def bandHandlerQE(data_file, high_symmetry_points, efermi, printall = True, sort = False, threshold = 0.1, window = [], index = []):
  """
  Args:
    data_file: Bands gnu data file generated by QE, 
    high_symmetry_points: High symmetry points, 
    efermi: efermi

  Args passed to _findBandgap:
    printall: If True prints all bandgaps
    sort: If the bands are unsorted and need sorting.
    threshold: Only gaps greater than threshold are considered. 
    index: Only keeps the bands that lie between the index limits. 
    window: Only keeps the bands that overlap with the window provided. 
  """
  data = np.loadtxt(data_file)
  k, bands = _process_band_structure(data) # Get k points and bands 
  positions, labels = _get_high_symmetry_positions_and_labels(k, high_symmetry_points)
 
  homolumo, bandgap = _findBandgap(bands,printall = printall, sort = sort, threshold = threshold, window = window, index = index)

  return k, bands, positions, labels, homolumo, bandgap


def _process_band_structure(data):
    """
    Functionailty

    Args: 
        data: type? list? dictionary?
    Returns: 

    """

    nbnd = len(np.where(np.diff(data[:, 0]) < 0)[0]) + 1
    lenk = int(data.shape[0] / nbnd)
    k = data[:lenk, 0]
    bands = np.reshape(data[:, 1], (-1, lenk))
    return k, bands

# Get the positions
def _get_high_symmetry_positions_and_labels(k, high_symmetry_points):
    positions = [k[index] for index in high_symmetry_points.values()]
    labels = list(high_symmetry_points.keys())
    return positions, labels










